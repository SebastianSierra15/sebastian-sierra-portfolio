create table if not exists public.analytics_events (
  id bigint generated by default as identity primary key,
  event_name text not null check (event_name in ('page_view', 'session_start', 'section_view', 'scroll_depth', 'project_view', 'project_cta', 'cv_download', 'contact_click', 'external_link_click', 'time_on_page', 'web_vital')),
  path text not null,
  session_id text,
  project_slug text,
  metadata jsonb not null default '{}'::jsonb,
  occurred_at timestamptz not null,
  created_at timestamptz not null default now()
);

create index if not exists analytics_events_occurred_at_idx on public.analytics_events (occurred_at desc);
create index if not exists analytics_events_name_idx on public.analytics_events (event_name);
create index if not exists analytics_events_project_idx on public.analytics_events (project_slug);

alter table public.analytics_events enable row level security;

